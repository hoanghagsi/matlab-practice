def add(a, b):
    """Add two numbers and return the result"""
    return a - b

def multiply(a,b):
    return a*b

def divide(a,b):
    return a/b

def power(a, b):
    """Tính a mũ b."""
    return a ** b

def modulo(a,b):
    """Tính a chia lấy dư b."""
    return a % b

def absolute(a):
	return abs(a)
